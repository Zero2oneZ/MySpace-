#!/usr/bin/env python3
"""scene_to_blender — transpile the canonical SCENE SPINE (MetaXR frame) into a Blender builder.

Blender is the ONE engine that diverges from the canonical frame: MetaXR is Y-up/-Z-forward,
Blender is Z-up/-Y-forward. So this applies the frame conversion (per gently asset_target.to_blender):
  MetaXR (x, y, z)  ->  Blender (x, -z, y)
Proves the ground layer handles the divergent technology, not just the identity ones (Godot/three).
Emits a standalone Blender python script (imports each GLB, places at converted transform).

  scene_to_blender.py [scene_spine.json] [out.py]
"""
import json, sys

SPINE = sys.argv[1] if len(sys.argv) > 1 else "/data/Projects/MySpace++/studio/scene_spine.json"
OUT   = sys.argv[2] if len(sys.argv) > 2 else "/tmp/scene_build_blender.py"
s = json.load(open(SPINE))

L = ["import bpy",
     f"# generated by scene_to_blender — spine={SPINE} frame={s.get('frame')} → Blender Z-up",
     "bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete()",
     "built = []"]
for n in s["nodes"]:
    p = n["pos"]
    bx, by, bz = p[0], -p[2], p[1]      # MetaXR Y-up → Blender Z-up
    L += [
        "before = set(o.name for o in bpy.data.objects)",
        f'bpy.ops.import_scene.gltf(filepath="{n["glb"]}")',
        "new = [o for o in bpy.data.objects if o.name not in before and o.parent is None]",
        "for o in new:",
        f"    o.location = ({bx}, {by}, {bz}); o.name = \"{n['id']}\"; built.append((o.name, tuple(o.location)))",
    ]
L += ['print("BLENDER_SPINE_BUILT objects=", len(built))',
      'for nm, loc in built: print("  obj=", nm, " @", loc)']
open(OUT, "w").write("\n".join(L) + "\n")
print(f"wrote {OUT} ({len(s['nodes'])} nodes)")
