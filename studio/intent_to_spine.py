#!/usr/bin/env python3
"""intent_to_spine — RUNG 5: the org/conductor DRIVES the scene. An intent (natural language) →
the executive model emits a canonical scene_spine.json → the engines consume it. Closes the loop
from agent-intent to a built scene. Reuses the conductor's executive (kimi cloud via /api/chat),
falls back to a local model. Output is normalized to the spine schema so a sloppy model can't break it.

  intent_to_spine.py "<intent>" [out_spine.json]
"""
import json, sys, re, urllib.request

INTENT = sys.argv[1] if len(sys.argv) > 1 else "a tiny character: a head sphere with a hand sphere on each side"
OUT    = sys.argv[2] if len(sys.argv) > 2 else "/data/Projects/MySpace++/studio/scene_spine.intent.json"
PALETTE = {"cube": "/tmp/e2e_proof.glb", "sphere": "/tmp/wrap_proof.glb"}

def ask(model, prompt):
    cloud = model.endswith(":cloud")
    url = "http://localhost:11434/api/" + ("chat" if cloud else "generate")
    b = {"model": model, "stream": False}
    b["messages" if cloud else "prompt"] = [{"role":"user","content":prompt}] if cloud else prompt
    if not cloud: b["format"] = "json"
    try:
        d = json.loads(urllib.request.urlopen(urllib.request.Request(url, json.dumps(b).encode(),
            {"Content-Type":"application/json"}), timeout=180).read())
        return "" if "error" in d else (d.get("message",{}).get("content","") if cloud else d.get("response","")).strip()
    except Exception: return ""

def norm(n):
    glb = n.get("glb") or PALETTE.get(str(n.get("asset","cube")).lower(), PALETTE["cube"])
    pos = n.get("pos") or [n.get("x",0), n.get("y",0), n.get("z",0)]
    pos = ([float(v) for v in pos] + [0,0,0])[:3]
    sc = n.get("scale", 0.2); sc = [sc,sc,sc] if isinstance(sc,(int,float)) else ([float(v) for v in sc]+[0.2,0.2,0.2])[:3]
    return {"id": re.sub(r'[^A-Za-z0-9_]','_',str(n.get("id","node")))[:32] or "node", "glb": glb,
            "pos": pos, "rot_euler_deg": [0,0,0], "scale": [float(v) for v in sc], "edit_mode": "link"}

prompt = (f'Output ONLY JSON: {{"nodes":[{{"id":"...","asset":"cube"|"sphere","pos":[x,y,z],"scale":n}}]}}.\n'
          f'Frame = MetaXR (Y-up, -Z forward, meters). Assets available: cube, sphere. Max 8 nodes.\n'
          f'Intent: {INTENT}')
raw, used = "", ""
for m in ["kimi-k2.6:cloud", "llama3.2:latest", "qwen3.5-chat:0.8b"]:
    raw = ask(m, prompt)
    if raw: used = m; break
mobj = re.search(r'\{.*\}', raw, re.S)
nodes = []
if mobj:
    try: nodes = [norm(n) for n in (json.loads(mobj.group(0)).get("nodes") or [])][:8]
    except Exception: pass
if not nodes:                                  # model failed → minimal honest fallback so the loop still closes
    nodes = [norm({"id":"fallback","asset":"cube","pos":[0,0,0]})]
spine = {"_doc": f"GENERATED by intent_to_spine — executive={used} — intent='{INTENT}'. Org drives the scene.",
         "frame": "MetaXR", "nodes": nodes}
json.dump(spine, open(OUT,"w"), indent=1)
print(f"intent → spine via {used or '(none)'}: {len(nodes)} nodes → {OUT}")
for n in nodes: print(f"  {n['id']:20} {n['glb'].split('/')[-1]:16} @{n['pos']}")
