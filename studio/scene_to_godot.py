#!/usr/bin/env python3
"""scene_to_godot — transpile the canonical SCENE SPINE (MetaXR frame) into a Godot scene builder.

Godot is MetaXR-identity (Y-up / -Z forward / meters), so spine transforms map 1:1 — no conversion.
This is the first "build up" rung on the GLB + frame ground: an engine that CONSUMES the spine.
Emits a headless-runnable .gd that loads each node's GLB and places it at its transform.

  scene_to_godot.py [scene_spine.json] [out.gd]
"""
import json, sys, math

SPINE = sys.argv[1] if len(sys.argv) > 1 else "/data/Projects/MySpace++/studio/scene_spine.json"
OUT   = sys.argv[2] if len(sys.argv) > 2 else "/tmp/scene_build.gd"
s = json.load(open(SPINE))

L = ["extends SceneTree",
     f"# generated by scene_to_godot — spine={SPINE} frame={s.get('frame')}",
     "func _init():",
     '\tvar root := Node3D.new(); root.name = "SceneRoot"']
for n in s["nodes"]:
    nid = n["id"]; p = n["pos"]; e = n["rot_euler_deg"]; sc = n["scale"]
    rx, ry, rz = (math.radians(v) for v in e)
    L += [
        f'\tvar st_{nid} := GLTFState.new()',
        f'\tvar doc_{nid} := GLTFDocument.new()',
        f'\tif doc_{nid}.append_from_file("{n["glb"]}", st_{nid}) == OK:',
        f'\t\tvar inst_{nid} = doc_{nid}.generate_scene(st_{nid})',
        f'\t\tinst_{nid}.name = "{nid}"',
        f'\t\tvar b_{nid} := Basis.from_euler(Vector3({rx:.6f},{ry:.6f},{rz:.6f})).scaled(Vector3({sc[0]},{sc[1]},{sc[2]}))',
        f'\t\tinst_{nid}.transform = Transform3D(b_{nid}, Vector3({p[0]},{p[1]},{p[2]}))',
        f'\t\troot.add_child(inst_{nid})',
        f'\telse: printerr("GLB_FAIL {nid}")',
    ]
L += ['\tprint("SPINE_BUILT root=", root.name, " nodes=", root.get_child_count())']
cp = s.get("camera_path") or []
if cp:
    L += [f'\tvar path := {json.dumps(cp)}',
          '\tvar cam := Camera3D.new(); cam.name = "WalkCam"; root.add_child(cam)',
          '\tprint("WALKTHROUGH waypoints=", path.size())',
          '\tfor i in range(path.size()):',
          '\t\tvar wp = path[i]; cam.position = Vector3(wp[0], wp[1], wp[2])',
          '\t\tif i + 1 < path.size() and Vector3(path[i+1][0],path[i+1][1],path[i+1][2]).distance_to(cam.position) > 0.01:',
          '\t\t\tcam.look_at(Vector3(path[i+1][0], path[i+1][1], path[i+1][2]))',
          '\t\tprint("  step ", i, " cam@", cam.position)']
L += ['\tquit(0)']
open(OUT, "w").write("\n".join(L) + "\n")
print(f"wrote {OUT} ({len(s['nodes'])} nodes)")
