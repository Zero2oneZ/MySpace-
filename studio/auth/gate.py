"""gate.py — Streamlit login gate with first-login IP binding.

Public API:
    require_login() -> AuthResult
        Renders a login form, looks up the user in permissions.jsonl, on
        success returns AuthResult(ok=True, user=..., email=...). On failure
        calls st.stop() so downstream app code never executes.

    get_client_ip() -> str
        Best-effort client IP. Tries (in order):
            1. Streamlit 1.32+ st.context.headers (X-Forwarded-For, X-Real-IP)
            2. websocket peer address via the script-run-ctx → session_mgr
            3. "127.0.0.1" as the loopback fallback (dev/CI)

Threat model: friend-scoped GPU sharing already gated by SSH at the
network layer. This module is the second factor — username + IP-bind on
top of SSH. Passwords are intentionally weak ("passwd") because the
strong factor is SSH key + IP binding.
"""
from __future__ import annotations

import hashlib
import json
import os
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

HERE = Path(__file__).resolve().parent
PERMISSIONS_PATH = Path(
    os.environ.get("MYSPACE_PERMISSIONS_PATH", str(HERE / "permissions.jsonl"))
)

LOOPBACK_IPS = {"127.0.0.1", "::1", "localhost"}


# ----------------------------------------------------------------------------
# Result type
# ----------------------------------------------------------------------------
@dataclass
class AuthResult:
    ok: bool
    user: Optional[str] = None
    email: Optional[str] = None
    ip: Optional[str] = None
    reason: Optional[str] = None
    solo: bool = False


# ----------------------------------------------------------------------------
# Hashing
# ----------------------------------------------------------------------------
def sha256(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def bind_hash(user: str, ip: str) -> str:
    """Identity hash bound to (username, client IP). Used as the per-session key."""
    return sha256(f"{user}:{ip}")


# ----------------------------------------------------------------------------
# Permissions store
# ----------------------------------------------------------------------------
def load_rows() -> list[dict]:
    if not PERMISSIONS_PATH.exists():
        return []
    rows: list[dict] = []
    with PERMISSIONS_PATH.open() as f:
        for ln in f:
            ln = ln.strip()
            if not ln or ln.startswith("#"):
                continue
            try:
                rows.append(json.loads(ln))
            except json.JSONDecodeError:
                continue
    return rows


def save_rows(rows: list[dict]) -> None:
    tmp = PERMISSIONS_PATH.with_suffix(".jsonl.tmp")
    with tmp.open("w") as f:
        f.write("# MySpace++ studio permissions — generated by auth.gate.\n")
        f.write("# Do not edit by hand; use seed_permissions.py or `cc -auth-grant`.\n")
        for r in rows:
            f.write(json.dumps(r, sort_keys=True) + "\n")
    os.replace(tmp, PERMISSIONS_PATH)
    try:
        os.chmod(PERMISSIONS_PATH, 0o600)
    except OSError:
        pass


def find_user(user: str) -> Optional[dict]:
    for r in load_rows():
        if r.get("user") == user:
            return r
    return None


def find_solo(email: str) -> Optional[dict]:
    """Solo row: user is null + email matches + solo=True."""
    for r in load_rows():
        if r.get("solo") and r.get("user") is None and r.get("email") == email:
            return r
    return None


# ----------------------------------------------------------------------------
# Verification (pure — testable without Streamlit)
# ----------------------------------------------------------------------------
def verify(
    user: Optional[str],
    passwd: Optional[str],
    client_ip: str,
    email: Optional[str] = None,
    *,
    now: Optional[float] = None,
    persist: bool = True,
) -> AuthResult:
    """Verify a login attempt. Pure-ish: only side-effect is persisting
    the binding on a successful first login (controlled by `persist`)."""
    now = now if now is not None else time.time()
    iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(now))

    rows = load_rows()
    row: Optional[dict] = None

    # Username path
    if user:
        for r in rows:
            if r.get("user") == user:
                row = r
                break
        if row is None:
            return AuthResult(ok=False, reason=f"unknown user: {user}")

    # Solo email path (no username given, email matches a solo row)
    elif email:
        for r in rows:
            if r.get("solo") and r.get("user") is None and r.get("email") == email:
                row = r
                break
        if row is None:
            return AuthResult(ok=False, reason="no matching solo row for email")

    else:
        return AuthResult(ok=False, reason="username or email required")

    if not row.get("permission"):
        return AuthResult(ok=False, reason="permission denied for this user")

    # Loopback-only check (the `localhost` row)
    if row.get("loopback_only") and client_ip not in LOOPBACK_IPS:
        return AuthResult(ok=False, reason="localhost row requires loopback IP")

    # Password check (only if a passwd_hash is set)
    expected_pwd = row.get("passwd_hash")
    if expected_pwd is not None:
        if passwd is None:
            return AuthResult(ok=False, reason="password required")
        if sha256(passwd) != expected_pwd:
            return AuthResult(ok=False, reason="wrong password")

    # IP-bind check
    bh = row.get("bind_hash")
    bound_ip = row.get("ip_bound")
    fresh_login = bh is None or bound_ip is None

    if fresh_login:
        # First successful login binds this user to this IP.
        row["bind_hash"] = bind_hash(user or row.get("email") or "(solo)", client_ip)
        row["ip_bound"] = client_ip
        row["first_seen"] = iso
        row["last_seen"] = iso
        if persist:
            save_rows(rows)
        return AuthResult(
            ok=True, user=row.get("user"), email=row.get("email"),
            ip=client_ip, solo=bool(row.get("solo")),
            reason="first-login bind",
        )

    # Subsequent login: IP must match the bound IP AND recomputed hash must match.
    if client_ip != bound_ip:
        return AuthResult(
            ok=False,
            reason=f"IP mismatch (request from {client_ip}, bound to {bound_ip})",
        )
    expected_bh = bind_hash(user or row.get("email") or "(solo)", client_ip)
    if expected_bh != bh:
        return AuthResult(ok=False, reason="bind hash mismatch (tampered store?)")

    row["last_seen"] = iso
    if persist:
        save_rows(rows)
    return AuthResult(
        ok=True, user=row.get("user"), email=row.get("email"),
        ip=client_ip, solo=bool(row.get("solo")),
    )


# ----------------------------------------------------------------------------
# Streamlit integration (imports streamlit lazily so this module is testable
# without streamlit installed).
# ----------------------------------------------------------------------------
def get_client_ip() -> str:
    """Best-effort client IP from a Streamlit request context."""
    # 1. Streamlit 1.32+ exposes request headers via st.context.
    try:
        import streamlit as st
        headers = getattr(st.context, "headers", None)
        if headers is not None:
            xff = headers.get("X-Forwarded-For") or headers.get("x-forwarded-for")
            if xff:
                return xff.split(",")[0].strip()
            xrip = headers.get("X-Real-IP") or headers.get("x-real-ip")
            if xrip:
                return xrip.strip()
    except Exception:
        pass

    # 2. Older Streamlit: walk into the runtime session manager.
    try:
        from streamlit.runtime.scriptrunner import get_script_run_ctx
        from streamlit.runtime import get_instance
        ctx = get_script_run_ctx()
        if ctx is not None:
            session = get_instance()._session_mgr.get_session_info(ctx.session_id)
            client = getattr(session, "client", None)
            req = getattr(client, "request", None) if client else None
            remote = getattr(req, "remote_ip", None) if req else None
            if remote:
                return str(remote)
    except Exception:
        pass

    # 3. Loopback fallback — typically the case when the app runs locally
    # and Streamlit hasn't forwarded headers.
    return "127.0.0.1"


def _autoseed_if_missing() -> None:
    """Friend-installable nicety: if permissions.jsonl doesn't exist yet,
    run the canonical seed so the gate has something to check against."""
    if PERMISSIONS_PATH.exists():
        return
    try:
        from . import seed_permissions as sp  # package context
    except (ImportError, ValueError):
        # Script context: add this dir to sys.path then import flat.
        import sys
        sys.path.insert(0, str(HERE))
        import seed_permissions as sp  # type: ignore
    sp.PERMISSIONS_PATH = PERMISSIONS_PATH
    rows = sp.merge(sp.SEED, [])
    sp.write(rows)


def require_login() -> AuthResult:
    """Streamlit gate. Call near the top of every entry-point script,
    immediately after st.set_page_config(). Halts the app on failure."""
    import streamlit as st

    _autoseed_if_missing()

    if "auth_result" in st.session_state and st.session_state["auth_result"].ok:
        return st.session_state["auth_result"]

    client_ip = get_client_ip()

    st.markdown("### Login")
    st.caption(
        "Friend-scoped access. Whitelisted username only — your IP "
        f"({client_ip}) will be bound to your account on first login."
    )

    with st.form("login_form", clear_on_submit=False):
        col_u, col_p = st.columns([2, 2])
        with col_u:
            user_in = st.text_input("Username", value="", autocomplete="username")
        with col_p:
            pw_in = st.text_input("Password (skip if whitelisted)", value="",
                                  type="password", autocomplete="current-password")
        email_in = st.text_input(
            "Or email (solo-mode fallback)",
            value="", placeholder="friends@Tmail.com",
            help="If you don't have a username, the solo email path may let you in.",
        )
        submit = st.form_submit_button("Sign in", type="primary")

    if not submit:
        st.stop()

    user = (user_in or "").strip() or None
    passwd = (pw_in or "") or None
    email = (email_in or "").strip() or None

    res = verify(user=user, passwd=passwd, client_ip=client_ip, email=email)
    if not res.ok:
        st.error(f"Login failed: {res.reason}")
        st.stop()

    st.session_state["auth_result"] = res
    if res.reason == "first-login bind":
        st.success(
            f"Welcome, {res.user or '(solo)'}! Your IP {res.ip} is now bound "
            "to this account. Subsequent logins must come from the same IP."
        )
    else:
        st.success(f"Signed in as {res.user or '(solo)'} from {res.ip}.")
    return res
