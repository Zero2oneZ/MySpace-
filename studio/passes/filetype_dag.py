"""filetype_dag.py — DAG indexed by file extension.

For a given imported file, this module answers two questions:

  1. "What passes are POSSIBLE on this file?" — for_filetype(ext)
  2. "Which run at IMPORT time vs LAZY?" — partitioned

Also emits a Mermaid diagram to studio/docs/PASSES_DAG.md describing the
filetype → pass graph.

This is a NEW DAG, complementary to the existing model-opcode DAG
(studio/nodes.py + studio/recipes.py). That one says "given an IMG, you
can run M_DEPTH, M_POSE, etc." THIS one says "given a `.jpg`, here's
the import-time vs lazy plan and which passes are in each tier."
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from passes import registry as reg


def plan_for(extension: str) -> dict:
    """Plan dict: {ext, import_time: [pass...], lazy: [pass...]}"""
    ext = extension.lower().lstrip(".")
    all_passes = reg.for_filetype(ext)
    return {
        "ext":        ext,
        "n_total":    len(all_passes),
        "import_time": [p.id for p in all_passes if p.import_time],
        "lazy":        [p.id for p in all_passes if not p.import_time],
    }


def all_extensions() -> list[str]:
    seen = set()
    for p in reg.REGISTRY:
        for e in p.file_extensions:
            seen.add(e.lower())
    return sorted(seen)


def to_mermaid() -> str:
    """Generate a Mermaid flowchart of filetype → pass edges."""
    lines = ["```mermaid", "flowchart LR"]
    # Group passes by extension, then by import/lazy.
    for ext in all_extensions():
        plan = plan_for(ext)
        node = f"F_{ext.upper()}[\".{ext}\"]"
        lines.append(f"  {node}")
        for pid in plan["import_time"]:
            p = reg.by_id(pid)
            lines.append(f"  {node} ==>|import| P_{pid.upper()}[\"{p.label}<br/><i>{p.cost_class}</i>\"]")
        for pid in plan["lazy"]:
            p = reg.by_id(pid)
            lines.append(f"  {node} -. lazy .-> P_{pid.upper()}[\"{p.label}<br/><i>{p.cost_class}</i>\"]")
    lines.append("```")
    return "\n".join(lines)


def write_doc() -> Path:
    """Write studio/docs/PASSES_DAG.md describing the per-filetype DAG."""
    import paths
    doc = paths.DOCS_ROOT / "PASSES_DAG.md"
    doc.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Passes DAG — by imported filetype",
        "",
        "Auto-generated by `studio/passes/filetype_dag.py`. Don't hand-edit.",
        "",
        "## Overview",
        "",
        f"- {len(reg.REGISTRY)} registered passes",
        f"- {len(all_extensions())} recognized file extensions",
        "",
        "## Per-filetype plan",
        "",
        "| Ext | Import-time (heavy stuff that runs once) | Lazy (on render) |",
        "|-----|-------------------------------------------|------------------|",
    ]
    for ext in all_extensions():
        plan = plan_for(ext)
        it = ", ".join(f"`{x}`" for x in plan["import_time"]) or "_(none)_"
        lz = ", ".join(f"`{x}`" for x in plan["lazy"]) or "_(none)_"
        lines.append(f"| `.{ext}` | {it} | {lz} |")

    lines += [
        "",
        "## Pass details",
        "",
        "| Pass | Cost | Stage | Inputs → Output | Description |",
        "|------|------|-------|----------------|-------------|",
    ]
    for p in reg.REGISTRY:
        stage = "import" if p.import_time else "lazy"
        ins = "+".join(p.input_kinds)
        lines.append(f"| **{p.id}** | {p.cost_class} | {stage} | "
                     f"{ins} → {p.output_kind} | {p.description} |")

    lines += [
        "",
        "## Mermaid graph",
        "",
        to_mermaid(),
        "",
    ]
    doc.write_text("\n".join(lines))
    return doc


if __name__ == "__main__":
    import json
    print(json.dumps(
        {ext: plan_for(ext) for ext in all_extensions()},
        indent=2,
    ))
    doc = write_doc()
    print(f"\nwrote {doc}", file=sys.stderr)
