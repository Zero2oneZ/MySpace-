# MySpace++ — Windows installer (container-only per OPEN_QUESTIONS Q5)
#
# What it does:
#   1. Checks for Docker Desktop (required — no native bash on Windows v1)
#   2. Builds the myspace-pp:local image from this repo
#   3. Drops a myspace.cmd wrapper in %USERPROFILE%\bin
#   4. Verifies install
#
# Usage (from PowerShell):
#   .\install.ps1
#   .\install.ps1 -Prefix C:\tools         # change install dir
#   .\install.ps1 -Uninstall               # remove
#
# Why container-only: bash on native Windows is a quagmire (path
# semantics, line endings, fork). Docker Desktop on Windows is mature
# and is already what most users in this audience have installed.

param(
    [string]$Prefix = "$env:USERPROFILE\bin",
    [switch]$Uninstall,
    [switch]$SkipVerify
)

$ErrorActionPreference = "Stop"

# --- colored output ------------------------------------------------------
function Say-Info($msg)  { Write-Host $msg -ForegroundColor Cyan }
function Say-Ok($msg)    { Write-Host $msg -ForegroundColor Green }
function Say-Warn($msg)  { Write-Host $msg -ForegroundColor Yellow }
function Say-Err($msg)   { Write-Host $msg -ForegroundColor Red }

# --- uninstall path ------------------------------------------------------
if ($Uninstall) {
    Say-Info "Uninstalling MySpace++..."
    $wrapper = Join-Path $Prefix "myspace.cmd"
    $alias   = Join-Path $Prefix "cc.cmd"
    if (Test-Path $wrapper) { Remove-Item $wrapper -Force }
    if (Test-Path $alias)   { Remove-Item $alias -Force }
    Say-Info "Removing Docker image myspace-pp:local..."
    docker image rm myspace-pp:local 2>$null
    Say-Ok "Removed. User data in %USERPROFILE%\.cc-home is NOT touched."
    exit 0
}

# --- repo root -----------------------------------------------------------
$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
Say-Info "Repo: $RepoRoot"

# --- Docker checks -------------------------------------------------------
$docker = Get-Command docker -ErrorAction SilentlyContinue
if (-not $docker) {
    Say-Err "Docker Desktop is required for MySpace++ on Windows."
    Write-Host ""
    Write-Host "Install Docker Desktop from:"
    Write-Host "  https://www.docker.com/products/docker-desktop/"
    Write-Host ""
    Write-Host "Alternative: use WSL2 and run ./install.sh from inside Linux."
    exit 1
}
Say-Ok "Docker found: $($docker.Source)"

# Docker daemon running?
$null = docker info 2>&1
if ($LASTEXITCODE -ne 0) {
    Say-Err "Docker is installed but the daemon is not running."
    Write-Host "Start Docker Desktop, wait for the whale icon to settle, then re-run."
    exit 1
}
Say-Ok "Docker daemon is running."

# --- build the image -----------------------------------------------------
Say-Info "Building myspace-pp:local Docker image (one-time, ~2 min)..."
Push-Location $RepoRoot
try {
    docker build -t myspace-pp:local .
    if ($LASTEXITCODE -ne 0) {
        Say-Err "Docker build failed."
        exit 1
    }
} finally {
    Pop-Location
}
Say-Ok "Image built."

# Report image size
$sizeRow = docker images myspace-pp:local --format "{{.Size}}"
Say-Info "Image size: $sizeRow"

# --- install wrapper -----------------------------------------------------
if (-not (Test-Path $Prefix)) {
    Say-Info "Creating $Prefix"
    New-Item -ItemType Directory -Path $Prefix | Out-Null
}

# The wrapper mounts:
#   %CD%                       → /workspace   (cwd inside container)
#   %USERPROFILE%\.cc-home     → /data        (CC_HOME, persistent)
# -it keeps tty for the curses tui / interactive prompts.
$wrapperPath = Join-Path $Prefix "myspace.cmd"
$wrapperBody = @"
@echo off
REM MySpace++ wrapper — auto-generated by install.ps1
docker run --rm -it ^
  -v "%CD%":/workspace ^
  -v "%USERPROFILE%\.cc-home":/data ^
  -e CC_HOME=/data ^
  myspace-pp:local %*
"@
Set-Content -Path $wrapperPath -Value $wrapperBody -Encoding ASCII

# Also drop a cc.cmd alias for back-compat with the original tool.
$aliasPath = Join-Path $Prefix "cc.cmd"
Set-Content -Path $aliasPath -Value $wrapperBody -Encoding ASCII

Say-Ok "Installed $wrapperPath"
Say-Ok "Installed $aliasPath"

# --- PATH check ----------------------------------------------------------
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if ($userPath -split ';' -notcontains $Prefix) {
    Say-Warn "$Prefix is not on your User PATH."
    Write-Host "Add it with:"
    Write-Host "  [Environment]::SetEnvironmentVariable('Path', `"$Prefix;`$([Environment]::GetEnvironmentVariable('Path','User'))`", 'User')"
    Write-Host "Then open a new PowerShell window."
} else {
    Say-Ok "$Prefix is already on your PATH."
}

# --- verify --------------------------------------------------------------
if (-not $SkipVerify) {
    Say-Info "Verifying..."
    & $wrapperPath -help | Out-Null
    if ($LASTEXITCODE -eq 0) {
        Say-Ok "Verification: PASS"
    } else {
        Say-Err "Verification: FAIL — 'myspace -help' didn't run cleanly inside the container."
        exit 1
    }
}

Write-Host ""
Say-Ok "MySpace++ installed."
Write-Host "Try it: $($wrapperPath) -help"
Write-Host "Or:     myspace -help    (after PATH is set)"
Write-Host ""
Write-Host "Next: cd to a project directory and run 'myspace -setup'"
Write-Host ""
Say-Info "Want the Streamlit Studio apps (Wardrobe / DAG / YouTube cutter)?"
Write-Host "  In this repo dir, run:"
Write-Host "    docker compose --profile studio up -d --build"
Write-Host "  Then open in your browser:"
Write-Host "    Wardrobe:        http://localhost:8510"
Write-Host "    DAG canvas:      http://localhost:8501"
Write-Host "    YouTube cutter:  http://localhost:8511"
