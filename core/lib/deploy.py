# role:        DISTRIBUTION · APP-GEN → SERVE → DROPLET ROUTING
# tier:        L0
# substrate:   local app generator (build-safe, no external Replit key needed)
#              + rsync→DigitalOcean droplet + Caddy route plan. Dry-run default.
# storage:     studio/deploy/generated/<slug>/  ·  studio/deploy/registry.json
# reuse:       studio/deploy/freetier_public/sync-games-build.sh (rsync pattern)
# ----------------------------------------------------------------------------
"""deploy.py — generate a full app locally, then serve/route it to the droplet.

The "Replit generates full apps" pipeline, build-safe: with no Replit API key we
scaffold a self-contained flat-HTML app under studio/deploy/generated/<slug>/ and
return a URL. `deploy` then plans (default) or applies an rsync to the DO droplet
where Caddy serves it. Nothing leaves the machine unless you pass --apply.

CLI:
  python3 core/lib/deploy.py generate <slug> [--title T] [--prompt P] [--card SLUG]
  python3 core/lib/deploy.py deploy   <slug> [--apply]      # default: dry-run plan
  python3 core/lib/deploy.py list
"""
from __future__ import annotations

import html
import json
import os
import subprocess
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

REPO = Path(__file__).resolve().parents[2]  # core/lib/deploy.py → project root
GENERATED_DIR = REPO / "studio" / "deploy" / "generated"
REGISTRY = REPO / "studio" / "deploy" / "registry.json"
CARDS_DIR = REPO / "studio" / "assets" / "_workflows"

# Droplet routing (overridable via env; mirrors sync-games-build.sh defaults).
DROPLET_HOST = os.environ.get("DROPLET_HOST", "root@159.89.181.146")
REMOTE_ROOT = os.environ.get("REMOTE_APPS_ROOT", "/opt/mspc-public/apps")
SSH_KEY = os.environ.get("MSPC_SSH_KEY", str(Path.home() / ".ssh" / "id_ed25519"))
PUBLIC_BASE = os.environ.get("MSPC_PUBLIC_BASE", "https://gentlyos.io/apps")


def _safe_slug(slug: str) -> str:
    return "".join(c for c in slug.lower() if c.isalnum() or c in "-_")[:48] or "app"


def _load_registry() -> Dict[str, Any]:
    try:
        return json.loads(REGISTRY.read_text())
    except Exception:
        return {"apps": {}}


def _save_registry(reg: Dict[str, Any]) -> None:
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(json.dumps(reg, indent=2))


# ── app generation (local, build-safe) ───────────────────────────────────────

_APP_TEMPLATE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title}</title>
<style>
 body{{margin:0;background:#0b0e14;color:#cbd5e1;font:15px/1.6 ui-monospace,Menlo,monospace;
   display:flex;min-height:100vh;align-items:center;justify-content:center;text-align:center}}
 .card{{max-width:640px;padding:40px}}
 h1{{font-size:28px;color:#e2e8f0;margin:0 0 12px}}
 .badge{{display:inline-block;padding:4px 10px;border-radius:12px;background:#134e4a;color:#a7f3eb;font-size:12px}}
 p{{color:#94a3b8}}
</style></head><body>
<div class="card">
 <div class="badge">MySpace++ · generated app</div>
 <h1>{title}</h1>
 <p>{prompt}</p>
 <p style="color:#475569;font-size:12px">slug: {slug} · built {built}</p>
</div></body></html>"""


def generate_app(slug: str, title: str = "", prompt: str = "",
                 card: str = "") -> Dict[str, Any]:
    """Scaffold a self-contained flat-HTML app under generated/<slug>/. If a
    workflow card slug is given, its title/description seed the page."""
    slug = _safe_slug(slug)
    if card:
        try:
            c = json.loads((CARDS_DIR / f"{card}.json").read_text())
            title = title or c.get("display_name") or c.get("name", slug)
            prompt = prompt or c.get("description", "")
        except Exception:
            pass
    title = title or slug.replace("-", " ").title()
    app_dir = GENERATED_DIR / slug
    app_dir.mkdir(parents=True, exist_ok=True)
    built = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    (app_dir / "index.html").write_text(_APP_TEMPLATE.format(
        title=html.escape(title), prompt=html.escape(prompt or "Generated by MySpace++."),
        slug=html.escape(slug), built=built))
    url = f"{PUBLIC_BASE}/{slug}/"
    reg = _load_registry()
    reg.setdefault("apps", {})[slug] = {
        "slug": slug, "title": title, "built": built,
        "local_path": str(app_dir), "url": url, "deployed": False}
    _save_registry(reg)
    return {"ok": True, "slug": slug, "title": title,
            "local_path": str(app_dir), "url": url,
            "files": [p.name for p in app_dir.iterdir()]}


# ── serve → droplet ───────────────────────────────────────────────────────────

def _rsync_argv(slug: str) -> List[str]:
    local = f"{GENERATED_DIR / slug}/"
    remote = f"{DROPLET_HOST}:{REMOTE_ROOT}/{slug}/"
    return ["rsync", "-az", "--delete", "-e", f"ssh -i {SSH_KEY} -o StrictHostKeyChecking=accept-new",
            local, remote]


def _caddy_route(slug: str) -> str:
    # Caddy serves the synced dir; one route per app under /apps/<slug>/.
    return (f"handle_path /apps/{slug}/* {{\n"
            f"    root * {REMOTE_ROOT}/{slug}\n    file_server\n}}")


def deploy(slug: str, apply: bool = False) -> Dict[str, Any]:
    """Plan (default) or apply (--apply) the rsync + Caddy route to the droplet.
    Build-safe: nothing leaves the machine unless apply=True."""
    slug = _safe_slug(slug)
    app_dir = GENERATED_DIR / slug
    if not app_dir.exists():
        return {"ok": False, "error": f"no generated app '{slug}' — run generate first"}
    argv = _rsync_argv(slug)
    plan = {
        "ok": True, "slug": slug, "apply": apply,
        "rsync": " ".join(argv),
        "caddy_route": _caddy_route(slug),
        "droplet": DROPLET_HOST, "remote": f"{REMOTE_ROOT}/{slug}/",
        "public_url": f"{PUBLIC_BASE}/{slug}/",
    }
    if not apply:
        plan["note"] = "dry-run — pass --apply to rsync to the droplet"
        return plan
    try:
        r = subprocess.run(argv, capture_output=True, timeout=120)
        plan["rsync_rc"] = r.returncode
        plan["rsync_err"] = r.stderr.decode("utf-8", "replace")[-500:] if r.returncode else ""
        if r.returncode == 0:
            reg = _load_registry()
            if slug in reg.get("apps", {}):
                reg["apps"][slug]["deployed"] = True
                _save_registry(reg)
    except FileNotFoundError:
        plan["ok"] = False; plan["error"] = "rsync not installed"
    except subprocess.TimeoutExpired:
        plan["ok"] = False; plan["error"] = "rsync timed out (droplet reachable over WireGuard?)"
    return plan


def list_apps() -> Dict[str, Any]:
    return _load_registry()


# ── CLI ──────────────────────────────────────────────────────────────────────

def main(argv: List[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd, args = argv[0], argv[1:]

    def opt(flag: str, default: str = "") -> str:
        return args[args.index(flag) + 1] if flag in args and args.index(flag) + 1 < len(args) else default

    if cmd == "generate":
        if not args:
            print("usage: generate <slug> [--title T] [--prompt P] [--card SLUG]"); return 2
        out = generate_app(args[0], title=opt("--title"), prompt=opt("--prompt"), card=opt("--card"))
        print(json.dumps(out, indent=2)); return 0
    if cmd == "deploy":
        if not args:
            print("usage: deploy <slug> [--apply]"); return 2
        print(json.dumps(deploy(args[0], apply="--apply" in args), indent=2)); return 0
    if cmd == "list":
        print(json.dumps(list_apps(), indent=2)); return 0
    print(f"unknown command: {cmd}"); return 2


if __name__ == "__main__":
    import sys
    raise SystemExit(main(sys.argv[1:]))
